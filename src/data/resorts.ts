/**
 * Resort stories for the "Выберите курорт" pop-up: a short read for first-time guests.
 * Photos are the site's own; `video` is a Russian-language travel film on YouTube about the resort
 * (shown as a picture with a link, not an embedded player). Never films or links of competing
 * booking sites.
 */
export interface ResortVideo {
  /** YouTube video id */
  id: string;
  /** what the film is about, in plain words */
  title: string;
  /** who made it */
  by: string;
}
/**
 * A photo from Wikimedia Commons under a free licence. The modal shows who made it and the licence,
 * linked to the file's page on Commons (the licence requires the credit).
 */
export interface SightPhoto {
  src: string;
  alt: string;
  /** author, as on Commons */
  by: string;
  /** «CC BY-SA 4.0» or «общественное достояние» */
  lic: string;
  /** file name on Commons: the credit links to its page */
  file: string;
  /** a painting: what and whose, shown instead of «Фото: …» */
  cap?: string;
  /** a wide picture (a triptych): shown whole, never cropped */
  wide?: boolean;
  /** which part to keep when the picture is cropped (CSS object-position) */
  pos?: string;
}
/** a place worth seeing, told for a guest of 60+: what it is, when and who built it, how to get there */
export interface Sight {
  t: string;
  /** when and who, in a few words */
  meta?: string;
  d: string;
  /** how to get there, in plain words */
  go?: string;
  photos: SightPhoto[];
}
export interface Resort {
  id: string;
  name: string;
  /** «Хочу в …»: the name after «в» (Палангу) */
  nameTo: string;
  tagline: string;
  hero: string;
  gallery: { src: string; alt: string }[];
  story: string[];
  /** 2–3 weeks told as a story: what a guest can do outside the sanatorium, week by week */
  weeks: { t: string; d: string }[];
  /** places worth seeing, each with a photo; calm things only — nothing a guest of 60+ would find hard */
  sights: Sight[];
  /** what else there is: museums, parks, beaches and water, evenings, day trips (not repeating the sights) */
  fun: { kind: FunKind; items: { t: string; d: string }[] }[];
  /** what to do when it rains */
  rain: string;
  facts: [string, string][];
  /** sanatoriums we sell here: name + id for the results page (empty id = no page yet) */
  sanatoriums: { name: string; id: string }[];
  video: ResortVideo | null;
  /** why people come here: 3–4 short reasons with a picture */
  why: { icon: ResortIcon; t: string; d: string }[];
  /** a usual day of a guest on treatment */
  day: { time: string; t: string; d?: string }[];
  /** good to know before the trip */
  tips: string[];
}

export type ResortIcon = 'water' | 'mud' | 'pine' | 'sea' | 'river' | 'quiet' | 'spa';
export type FunKind = 'museum' | 'park' | 'water' | 'evening' | 'trip';

